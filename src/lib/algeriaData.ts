/**
 * Format currency in Algerian Dinars (DZD)
 */
export function formatDZD(amount: number | string, includeSuffix = true): string {
  const num = typeof amount === 'string' ? parseFloat(amount) || 0 : amount;
  const formatted = new Intl.NumberFormat('ar-DZ', {
    maximumFractionDigits: 0,
    minimumFractionDigits: 0,
  }).format(Math.round(num));

  return includeSuffix ? `${formatted} دج` : formatted;
}

/**
 * Format Algerian phone number for display (e.g. 0550 12 34 56)
 */
export function formatAlgerianPhone(phone: string): string {
  if (!phone) return '';
  const cleaned = phone.replace(/\D/g, '');
  if (cleaned.length === 10) {
    return `${cleaned.substring(0, 4)} ${cleaned.substring(4, 6)} ${cleaned.substring(6, 8)} ${cleaned.substring(8, 10)}`;
  }
  return phone;
}

/**
 * Clean phone number to Algerian WhatsApp international format (+213...)
 */
export function getWhatsAppUrl(phone: string, message = ''): string {
  if (!phone) return '';
  let cleaned = phone.replace(/\D/g, '');
  if (cleaned.startsWith('0')) {
    cleaned = '213' + cleaned.substring(1);
  } else if (!cleaned.startsWith('213')) {
    cleaned = '213' + cleaned;
  }
  const encoded = encodeURIComponent(message);
  return `https://wa.me/${cleaned}${encoded ? `?text=${encoded}` : ''}`;
}

